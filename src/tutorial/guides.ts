/** Every full-guide section can also be replayed as a focused module. */
export const MODULE_TUTORIAL_GUIDES: readonly TutorialGuide[] =
  FULL_TUTORIAL_GUIDE.sections!.map((section) => {
    const steps = FULL_TUTORIAL_GUIDE.steps.filter(
      (tutorialStep) => tutorialStep.sectionId === section.id,
    );
    const first = steps[0];
    return {
      id: `module:${section.id}`,
      version: FULL_TUTORIAL_GUIDE.version,
      title: `${section.title} guide`,
      detail: section.detail ?? `Focused walkthrough of ${section.title}`,
      icon: MODULE_ICONS[section.id] ?? "compass-outline",
      path: first?.navigation?.before ?? first?.path ?? FULL_TUTORIAL_GUIDE.path,
      sections: [section],
      steps,
    };
  });

export const TUTORIAL_GUIDES: readonly TutorialGuide[] = [
  BASIC_TUTORIAL_GUIDE,
  FULL_TUTORIAL_GUIDE,
  ...MODULE_TUTORIAL_GUIDES,
];

export const TUTORIAL_ANCHOR_INVENTORY = [...new Set(
  TUTORIAL_GUIDES.flatMap((guide) => guide.steps.flatMap((item) => item.target ? [item.target] : [])),
)].sort();

export const TUTORIAL_ROUTE_INVENTORY = [...new Set(
  TUTORIAL_GUIDES.flatMap((guide) => guide.steps.flatMap((item) => [
    item.path,
    item.navigation?.before,
    item.navigation?.after,
  ].filter((route): route is string => Boolean(route)))),
)].sort();
