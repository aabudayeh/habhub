type StepInput = Omit<TutorialStep, "sectionId" | "anchor" | "interaction"> & {
  target?: string;
  required?: boolean;
  practice?: {
    actionId: `tutorial.${string}`;
    instruction: string;
    completion?: "tap-anchor" | "observed-action";
    autoAdvance?: boolean;
  };
};

const step = (sectionId: string, input: StepInput): TutorialStep => ({
  ...input,
  sectionId,
  anchor: input.target
    ? {
        required: input.required ?? true,
        waitMs: input.required === false ? 900 : 2200,
        padding: 7,
        radius: 16,
      }
    : undefined,
  interaction: input.practice
    ? {
        mode: "practice",
        actionId: input.practice.actionId,
        instruction: input.practice.instruction,
        completion: input.practice.completion ?? "observed-action",
        autoAdvance: input.practice.autoAdvance,
      }
    : { mode: "observe", completion: "manual" },
});

